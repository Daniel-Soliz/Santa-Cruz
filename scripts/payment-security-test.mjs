import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { verifyMercadoPagoSignature, amountMatches } from '../src/server/paymentSecurity.ts';

const secret = 'teste-webhook-segredo-exclusivo';
const dataId = '1234567';
const requestId = 'request-id-teste';
const now = Date.now();
const ts = String(now);
const manifest = `id:${dataId};request-id:${requestId};ts:${ts};`;
const sig = crypto.createHmac('sha256', secret).update(manifest).digest('hex');
const valid = { dataId, requestId, signature: `ts=${ts},v1=${sig}`, secret, now };
assert.equal(verifyMercadoPagoSignature(valid), true, 'Assinatura correta precisa ser aceita');
assert.equal(verifyMercadoPagoSignature({...valid, dataId:'999'}), false, 'ID alterado precisa ser rejeitado');
assert.equal(verifyMercadoPagoSignature({...valid, requestId:'outro'}), false, 'Request ID alterado precisa ser rejeitado');
assert.equal(verifyMercadoPagoSignature({...valid, secret:'outra-chave'}), false, 'Chave errada precisa ser rejeitada');
assert.equal(verifyMercadoPagoSignature({...valid, now:now + 10*60*1000}), false, 'Notificação expirada deve ser rejeitada');
assert.equal(verifyMercadoPagoSignature({...valid, signature:'ts=123,v1=123'}), false, 'Assinatura incompleta deve ser rejeitada');
assert.equal(amountMatches(49.90,49.9), true);
assert.equal(amountMatches(49.91,49.90), false);
assert.equal(amountMatches('49.90',49.90), false);
console.log('Assinatura HMAC, tolerância de tempo e valores de pagamento validados.');
